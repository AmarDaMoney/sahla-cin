// Pluriel arabe : 1, 2, 3–10, 11 et plus.
function count(n: number, forms: { one: string; two: string; few: string; many: string }) {
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  const rest = n % 100;
  if (rest >= 3 && rest <= 10) return `${n} ${forms.few}`;
  return `${n} ${forms.many}`;
}

